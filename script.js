const ROUND_SIZE = 15;
const els = {
  paletteSelect: document.getElementById('paletteSelect'),
  modeToggle: document.getElementById('modeToggle'),
  progressText: document.getElementById('progressText'),
  scoreText: document.getElementById('scoreText'),
  progressBar: document.getElementById('progressBar'),
  questionText: document.getElementById('questionText'),
  answers: document.getElementById('answers'),
  feedbackCard: document.getElementById('feedbackCard'),
  resultTitle: document.getElementById('resultTitle'),
  correctShort: document.getElementById('correctShort'),
  explanationText: document.getElementById('explanationText'),
  nextBtn: document.getElementById('nextBtn'),
  quizCard: document.getElementById('quizCard'),
  finalCard: document.getElementById('finalCard'),
  finalText: document.getElementById('finalText'),
  restartBtn: document.getElementById('restartBtn')
};

let roundQuestions = [];
let index = 0;
let score = 0;

const shuffle = (arr) => {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
};

const setTheme = (mode) => {
  document.documentElement.dataset.theme = mode;
  localStorage.setItem('theme-mode', mode);
  els.modeToggle.textContent = mode === 'dark' ? '☀️ Svijetli način' : '🌙 Tamni način';
};

const setPalette = (palette) => {
  document.documentElement.dataset.palette = palette;
  localStorage.setItem('theme-palette', palette);
  els.paletteSelect.value = palette;
};

const loadPreferences = () => {
  setTheme(localStorage.getItem('theme-mode') || 'light');
  setPalette(localStorage.getItem('theme-palette') || 'sunset');
};

const currentQuestion = () => roundQuestions[index];

const updateProgress = () => {
  const current = Math.min(index + 1, ROUND_SIZE);
  els.progressText.textContent = `Pitanje ${current}/${ROUND_SIZE}`;
  els.scoreText.textContent = `Bodovi: ${score}`;
  els.progressBar.style.width = `${(index / ROUND_SIZE) * 100}%`;
};

const showFinal = () => {
  els.quizCard.hidden = true;
  els.feedbackCard.hidden = true;
  els.finalCard.hidden = false;
  els.progressText.textContent = `Pitanje ${ROUND_SIZE}/${ROUND_SIZE}`;
  els.progressBar.style.width = '100%';
  const postotak = Math.round((score / ROUND_SIZE) * 100);
  els.finalText.textContent = `Riješio/la si ${score} od ${ROUND_SIZE} pitanja (${postotak}%).`;
};

const showQuestion = () => {
  if (index >= ROUND_SIZE) {
    showFinal();
    return;
  }

  const q = currentQuestion();
  els.quizCard.hidden = false;
  els.feedbackCard.hidden = true;
  els.finalCard.hidden = true;

  els.questionText.textContent = q.question;
  els.answers.innerHTML = '';

  const optionEntries = Object.entries(q.options).map(([letter, text]) => ({ letter, text }));
  shuffle(optionEntries).forEach((opt) => {
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = 'answer';
    btn.innerHTML = `<strong>${opt.letter}.</strong> ${opt.text}`;
    btn.addEventListener('click', () => submitAnswer(opt.letter));
    els.answers.appendChild(btn);
  });

  updateProgress();
};

const submitAnswer = (selected) => {
  const q = currentQuestion();
  const isCorrect = selected === q.correct;
  if (isCorrect) score += 1;

  els.feedbackCard.hidden = false;
  els.feedbackCard.classList.toggle('ok', isCorrect);
  els.feedbackCard.classList.toggle('bad', !isCorrect);
  els.resultTitle.textContent = isCorrect ? 'Točno! ✅' : 'Netočno! ❌';
  els.correctShort.textContent = `${q.correct}. ${q.options[q.correct]}`;
  els.explanationText.textContent = q.explanation;

  els.quizCard.hidden = true;
  updateProgress();
};

const startRound = () => {
  roundQuestions = shuffle(QUESTION_BANK).slice(0, ROUND_SIZE);
  index = 0;
  score = 0;
  showQuestion();
};

els.nextBtn.addEventListener('click', () => {
  index += 1;
  showQuestion();
});

els.restartBtn.addEventListener('click', startRound);
els.modeToggle.addEventListener('click', () => {
  setTheme(document.documentElement.dataset.theme === 'dark' ? 'light' : 'dark');
});
els.paletteSelect.addEventListener('change', (e) => setPalette(e.target.value));

loadPreferences();
startRound();
